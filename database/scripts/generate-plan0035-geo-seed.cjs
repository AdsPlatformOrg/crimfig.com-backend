#!/usr/bin/env node
/**
 * Generate the PLAN-0035 migration from the vendored ISO datasets.
 *
 * Sources (vendored in ../seed-data):
 *   - lukes/ISO-3166-Countries-with-Regional-Codes (all.json)
 *   - olahol/iso-3166-2.json
 *
 * Output: ../migrations/0018_plan0035_ad_stacks_geo.sql
 * The output is committed. Re-run only when the datasets or mapping change.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const COUNTRIES = JSON.parse(fs.readFileSync(path.join(ROOT, 'seed-data/iso3166-countries.json'), 'utf8'));
const SUBDIVISIONS = JSON.parse(fs.readFileSync(path.join(ROOT, 'seed-data/iso3166-subdivisions.json'), 'utf8'));
const OUT = path.join(ROOT, 'migrations/0018_plan0035_ad_stacks_geo.sql');
const GEO_VERSION = 'crimfig-geo-2026.10';

const regionBySubregion = {
  'Northern Africa': ['northern-africa', 'Northern Africa'],
  'Western Africa': ['western-africa', 'Western Africa'],
  'Middle Africa': ['middle-africa', 'Middle Africa'],
  'Eastern Africa': ['eastern-africa', 'Eastern Africa'],
  'Southern Africa': ['southern-africa', 'Southern Africa'],
  'Northern America': ['northern-america', 'Northern America'],
  'Central America': ['central-america', 'Central America'],
  'Caribbean': ['caribbean', 'Caribbean'],
  'South America': ['south-america', 'South America'],
  'Central Asia': ['central-asia', 'Central Asia'],
  'Eastern Asia': ['eastern-asia', 'Eastern Asia'],
  'South-Eastern Asia': ['south-eastern-asia', 'South-Eastern Asia'],
  'South-eastern Asia': ['south-eastern-asia', 'South-Eastern Asia'],
  'Southern Asia': ['southern-asia', 'Southern Asia'],
  'Western Asia': ['western-asia', 'Western Asia'],
  'Northern Europe': ['northern-europe', 'Northern Europe'],
  'Southern Europe': ['southern-europe', 'Southern Europe'],
  'Eastern Europe': ['eastern-europe', 'Eastern Europe'],
  'Western Europe': ['western-europe', 'Western Europe'],
  'Australia and New Zealand': ['australia-new-zealand', 'Australia and New Zealand'],
  'Melanesia': ['melanesia', 'Melanesia'],
  'Micronesia': ['micronesia', 'Micronesia'],
  'Polynesia': ['polynesia', 'Polynesia'],
};

const continentByRegion = {
  'northern-africa': ['africa', 'Africa'],
  'western-africa': ['africa', 'Africa'],
  'middle-africa': ['africa', 'Africa'],
  'eastern-africa': ['africa', 'Africa'],
  'southern-africa': ['africa', 'Africa'],
  'northern-america': ['north-america', 'North America'],
  'central-america': ['north-america', 'North America'],
  'caribbean': ['north-america', 'North America'],
  'south-america': ['south-america', 'South America'],
  'central-asia': ['asia', 'Asia'],
  'eastern-asia': ['asia', 'Asia'],
  'south-eastern-asia': ['asia', 'Asia'],
  'southern-asia': ['asia', 'Asia'],
  'western-asia': ['asia', 'Asia'],
  'northern-europe': ['europe', 'Europe'],
  'southern-europe': ['europe', 'Europe'],
  'eastern-europe': ['europe', 'Europe'],
  'western-europe': ['europe', 'Europe'],
  'australia-new-zealand': ['oceania', 'Oceania'],
  'melanesia': ['oceania', 'Oceania'],
  'micronesia': ['oceania', 'Oceania'],
  'polynesia': ['oceania', 'Oceania'],
  'antarctica': ['antarctica', 'Antarctica'],
};

// The source dataset splits Africa and the Americas into broad sub-regions and
// carries the useful macro-region in `intermediate-region`. Resolve either.
function resolveRegion(country) {
  if (country['alpha-2'] === 'AQ') return ['antarctica', 'Antarctica'];
  if (country['alpha-2'] === 'TW') return ['eastern-asia', 'Eastern Asia'];
  return regionBySubregion[country['sub-region']] || regionBySubregion[country['intermediate-region']] || null;
}

function q(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function normalize(value) {
  return String(value)
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();
}

const continents = [
  ['africa', 'Africa'],
  ['asia', 'Asia'],
  ['europe', 'Europe'],
  ['north-america', 'North America'],
  ['south-america', 'South America'],
  ['oceania', 'Oceania'],
  ['antarctica', 'Antarctica'],
];

const regions = new Map();
for (const country of COUNTRIES) {
  if (!country['alpha-2']) continue;
  const mapped = resolveRegion(country);
  if (!mapped) continue;
  regions.set(mapped[0], mapped[1]);
}
regions.set('antarctica', 'Antarctica');

const lines = [];
lines.push('-- PLAN-0035: Ad Stacks, canonical geography, ad types, and legacy backfill.');
lines.push('-- Generated by scripts/generate-plan0035-geo-seed.cjs from the vendored ISO datasets.');
lines.push('-- Do not hand-edit the seed rows; update the datasets and regenerate instead.');
lines.push('');
lines.push('CREATE TABLE IF NOT EXISTS "ads_creative_stacks" (');
lines.push('  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,');
lines.push('  "campaign_id" uuid NOT NULL,');
lines.push('  "name" varchar(100) NOT NULL,');
lines.push('  "position" integer NOT NULL,');
lines.push("  \"geo_mode\" varchar(16) DEFAULT 'inherit' NOT NULL,");
lines.push('  "target_devices" text,');
lines.push('  "target_hours" text,');
lines.push('  "created_at" timestamp with time zone DEFAULT now() NOT NULL,');
lines.push('  "updated_at" timestamp with time zone DEFAULT now() NOT NULL');
lines.push(');');
lines.push('ALTER TABLE "ads_creative_stacks" DROP CONSTRAINT IF EXISTS "ads_creative_stacks_campaign_id_ads_campaigns_id_fk";');
lines.push('ALTER TABLE "ads_creative_stacks" ADD CONSTRAINT "ads_creative_stacks_campaign_id_ads_campaigns_id_fk" FOREIGN KEY ("campaign_id") REFERENCES "ads_campaigns"("id") ON DELETE cascade;');
lines.push('CREATE UNIQUE INDEX IF NOT EXISTS "ads_creative_stacks_campaign_position_uq" ON "ads_creative_stacks" ("campaign_id","position");');
lines.push('CREATE INDEX IF NOT EXISTS "ads_creative_stacks_campaign_id_idx" ON "ads_creative_stacks" ("campaign_id");');
lines.push('');
lines.push('CREATE TABLE IF NOT EXISTS "crimfig_geo_places" (');
lines.push('  "id" varchar(160) PRIMARY KEY NOT NULL,');
lines.push('  "scope" varchar(16) NOT NULL,');
lines.push('  "parent_id" varchar(160),');
lines.push('  "name" text NOT NULL,');
lines.push('  "normalized_name" text NOT NULL,');
lines.push('  "country_code" varchar(2),');
lines.push('  "subdivision_code" varchar(16),');
lines.push('  "latitude" double precision,');
lines.push('  "longitude" double precision,');
lines.push('  "geo_version" varchar(40) NOT NULL,');
lines.push('  "source_provider" varchar(20),');
lines.push('  "source_place_id" text,');
lines.push('  "created_at" timestamp with time zone DEFAULT now() NOT NULL');
lines.push(');');
lines.push('CREATE INDEX IF NOT EXISTS "crimfig_geo_places_scope_idx" ON "crimfig_geo_places" ("scope");');
lines.push('CREATE INDEX IF NOT EXISTS "crimfig_geo_places_parent_idx" ON "crimfig_geo_places" ("parent_id");');
lines.push('CREATE INDEX IF NOT EXISTS "crimfig_geo_places_country_idx" ON "crimfig_geo_places" ("country_code");');
lines.push("CREATE UNIQUE INDEX IF NOT EXISTS \"crimfig_geo_places_city_name_uq\" ON \"crimfig_geo_places\" (\"parent_id\",\"normalized_name\",\"geo_version\") WHERE scope = 'city';");
lines.push('');
lines.push('CREATE TABLE IF NOT EXISTS "crimfig_geo_targets" (');
lines.push('  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,');
lines.push('  "owner_type" varchar(16) NOT NULL,');
lines.push('  "owner_id" uuid NOT NULL,');
lines.push('  "place_id" varchar(160) NOT NULL,');
lines.push('  "scope" varchar(16) NOT NULL,');
lines.push('  "geo_version" varchar(40) NOT NULL,');
lines.push("  \"resolved_countries\" text DEFAULT '[]' NOT NULL,");
lines.push("  \"resolved_subdivisions\" text DEFAULT '[]' NOT NULL,");
lines.push("  \"resolved_cities\" text DEFAULT '[]' NOT NULL,");
lines.push('  "created_at" timestamp with time zone DEFAULT now() NOT NULL');
lines.push(');');
lines.push('CREATE UNIQUE INDEX IF NOT EXISTS "crimfig_geo_targets_owner_place_uq" ON "crimfig_geo_targets" ("owner_type","owner_id","place_id");');
lines.push('CREATE INDEX IF NOT EXISTS "crimfig_geo_targets_owner_idx" ON "crimfig_geo_targets" ("owner_type","owner_id");');
lines.push('');
lines.push('DO $$ BEGIN');
lines.push("  CREATE TYPE \"public\".\"ads_creative_ad_type\" AS ENUM ('text','image','video');");
lines.push('EXCEPTION WHEN duplicate_object THEN NULL; END $$;');
lines.push('');
lines.push("ALTER TABLE \"ads_campaigns\" ADD COLUMN IF NOT EXISTS \"geo_mode\" varchar(16) DEFAULT 'global' NOT NULL;");
lines.push('ALTER TABLE "ads_campaigns" ADD COLUMN IF NOT EXISTS "category" varchar(80);');
lines.push('ALTER TABLE "ads_campaigns" ADD COLUMN IF NOT EXISTS "channels" text;');
// The schema had this column without a committed migration; add it defensively
// so a database built from the journal is complete. Production already has it.
lines.push('ALTER TABLE "ads_campaigns" ADD COLUMN IF NOT EXISTS "is_bonus_delivery" boolean DEFAULT false NOT NULL;');
lines.push('');
lines.push('ALTER TABLE "ads_creatives" ADD COLUMN IF NOT EXISTS "ad_stack_id" uuid;');
lines.push("ALTER TABLE \"ads_creatives\" ADD COLUMN IF NOT EXISTS \"ad_type\" \"public\".\"ads_creative_ad_type\" DEFAULT 'text' NOT NULL;");
lines.push('ALTER TABLE "ads_creatives" ADD COLUMN IF NOT EXISTS "poster_url" text;');
lines.push('');
lines.push('-- One default stack per existing campaign, then assign every existing creative.');
lines.push('INSERT INTO "ads_creative_stacks" ("campaign_id","name","position")');
lines.push("SELECT c.id, 'Ad Stack #1', 1 FROM \"ads_campaigns\" c");
lines.push('WHERE NOT EXISTS (SELECT 1 FROM "ads_creative_stacks" s WHERE s.campaign_id = c.id);');
lines.push('UPDATE "ads_creatives" cr SET "ad_stack_id" = s.id');
lines.push('FROM "ads_creative_stacks" s');
lines.push('WHERE s.campaign_id = cr.campaign_id AND s.position = 1 AND cr.ad_stack_id IS NULL;');
lines.push('ALTER TABLE "ads_creatives" ALTER COLUMN "ad_stack_id" SET NOT NULL;');
lines.push('ALTER TABLE "ads_creatives" DROP CONSTRAINT IF EXISTS "ads_creatives_ad_stack_id_ads_creative_stacks_id_fk";');
lines.push('ALTER TABLE "ads_creatives" ADD CONSTRAINT "ads_creatives_ad_stack_id_ads_creative_stacks_id_fk" FOREIGN KEY ("ad_stack_id") REFERENCES "ads_creative_stacks"("id") ON DELETE restrict;');
lines.push('CREATE INDEX IF NOT EXISTS "ads_creatives_stack_id_idx" ON "ads_creatives" ("ad_stack_id");');
lines.push('');
lines.push("-- Derive legacy ad type from real asset references. Ambiguous rows default to text and are reported by the validation script.");
lines.push("UPDATE \"ads_creatives\" SET \"ad_type\" = 'video' WHERE \"video_url\" IS NOT NULL AND \"video_url\" <> '';");
lines.push("UPDATE \"ads_creatives\" SET \"ad_type\" = 'image' WHERE (\"video_url\" IS NULL OR \"video_url\" = '') AND \"image_url\" IS NOT NULL AND \"image_url\" <> '';");
lines.push('');
lines.push('-- Explicitly mark campaigns that already carried country/state targeting, then map');
lines.push('-- recognizable countries. Unmatched legacy values remain readable in the old columns.');
lines.push("UPDATE \"ads_campaigns\" SET \"geo_mode\" = 'targeted'");
lines.push("WHERE (\"target_countries\" IS NOT NULL AND \"target_countries\" <> '[]')");
lines.push("   OR (\"target_states\" IS NOT NULL AND \"target_states\" <> '[]');");
lines.push('');
lines.push('INSERT INTO "crimfig_geo_targets" ("owner_type","owner_id","place_id","scope","geo_version","resolved_countries","resolved_subdivisions")');
lines.push("SELECT 'campaign', c.id, 'country:' || upper(cc), 'country', " + q(GEO_VERSION) + ',');
lines.push("       jsonb_build_array(upper(cc))::text, '[]'");
lines.push('FROM "ads_campaigns" c');
lines.push("CROSS JOIN LATERAL jsonb_array_elements_text(c.target_countries::jsonb) AS cc");
lines.push("WHERE c.target_countries IS NOT NULL AND c.target_countries LIKE '[%'");
lines.push('ON CONFLICT ("owner_type","owner_id","place_id") DO NOTHING;');
lines.push('');
lines.push('INSERT INTO "crimfig_geo_targets" ("owner_type","owner_id","place_id","scope","geo_version","resolved_countries","resolved_subdivisions")');
lines.push("SELECT 'campaign', c.id, 'state:' || p.subdivision_code, 'state', " + q(GEO_VERSION) + ',');
lines.push('       CASE WHEN p.country_code IS NULL THEN \'[]\' ELSE jsonb_build_array(p.country_code)::text END,');
lines.push("       jsonb_build_array(p.subdivision_code)::text");
lines.push('FROM "ads_campaigns" c');
lines.push("CROSS JOIN LATERAL jsonb_array_elements_text(c.target_states::jsonb) AS st");
lines.push('JOIN "crimfig_geo_places" p ON p.scope = \'state\'');
lines.push("  AND p.geo_version = " + q(GEO_VERSION));
lines.push("  AND p.normalized_name = btrim(regexp_replace(lower(st), '[^a-z0-9]+', ' ', 'g'))");
lines.push("  AND (c.target_countries IS NULL OR p.country_code IN (SELECT upper(x) FROM jsonb_array_elements_text(c.target_countries::jsonb) x))");
lines.push("WHERE c.target_states IS NOT NULL AND c.target_states LIKE '[%'");
lines.push('ON CONFLICT ("owner_type","owner_id","place_id") DO NOTHING;');
lines.push('');

function insertPlaces(rows) {
  const chunks = [];
  for (let i = 0; i < rows.length; i += 400) chunks.push(rows.slice(i, i + 400));
  for (const chunk of chunks) {
    lines.push('INSERT INTO "crimfig_geo_places" ("id","scope","parent_id","name","normalized_name","country_code","subdivision_code","geo_version","source_provider") VALUES');
    lines.push(chunk.map((r) => `(${r.map((v) => (v === null ? 'NULL' : q(v))).join(',')})`).join(',\n') + '\nON CONFLICT ("id") DO NOTHING;');
  }
}

const placeRows = [];
for (const [slug, name] of continents) {
  placeRows.push([`continent:${slug}`, 'continent', null, name, normalize(name), null, null, GEO_VERSION, null]);
}
for (const [slug, name] of regions) {
  const continent = continentByRegion[slug];
  placeRows.push([`region:${slug}`, 'region', continent ? `continent:${continent[0]}` : null, name, normalize(name), null, null, GEO_VERSION, null]);
}
for (const country of COUNTRIES) {
  const code = country['alpha-2'];
  const region = resolveRegion(country);
  if (!code || !region) continue;
  placeRows.push([`country:${code}`, 'country', `region:${region[0]}`, country.name, normalize(country.name), code, null, GEO_VERSION, null]);
}
for (const [code, entry] of Object.entries(SUBDIVISIONS)) {
  if (!entry || !entry.divisions || !entry.name) continue;
  for (const [subCode, name] of Object.entries(entry.divisions)) {
    if (!name) continue;
    placeRows.push([`state:${subCode}`, 'state', `country:${code}`, name, normalize(name), code, subCode, GEO_VERSION, null]);
  }
}
insertPlaces(placeRows);
lines.push('');
lines.push('-- State mapping runs after the seed so canonical subdivisions exist.');
lines.push('INSERT INTO "crimfig_geo_targets" ("owner_type","owner_id","place_id","scope","geo_version","resolved_countries","resolved_subdivisions")');
lines.push("SELECT 'campaign', c.id, 'state:' || p.subdivision_code, 'state', " + q(GEO_VERSION) + ',');
lines.push("       CASE WHEN p.country_code IS NULL THEN '[]' ELSE jsonb_build_array(p.country_code)::text END,");
lines.push("       jsonb_build_array(p.subdivision_code)::text");
lines.push('FROM "ads_campaigns" c');
lines.push("CROSS JOIN LATERAL jsonb_array_elements_text(c.target_states::jsonb) AS st");
lines.push('JOIN "crimfig_geo_places" p ON p.scope = \'state\'');
lines.push("  AND p.geo_version = " + q(GEO_VERSION));
lines.push("  AND p.normalized_name = btrim(regexp_replace(lower(st), '[^a-z0-9]+', ' ', 'g'))");
lines.push("  AND (c.target_countries IS NULL OR p.country_code IN (SELECT upper(x) FROM jsonb_array_elements_text(c.target_countries::jsonb) x))");
lines.push("WHERE c.target_states IS NOT NULL AND c.target_states LIKE '[%'");
lines.push('ON CONFLICT ("owner_type","owner_id","place_id") DO NOTHING;');
lines.push('');

fs.writeFileSync(OUT, lines.join('\n'), 'utf8');
console.log(`Wrote ${OUT}`);
console.log(`continents=${continents.length} regions=${regions.size} places=${placeRows.length} countries=${COUNTRIES.length} subdivisions=${Object.keys(SUBDIVISIONS).length}`);
